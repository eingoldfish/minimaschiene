const DICTIONARIES: Record<Language, Dictionary> = { de, en };

let current: Language = 'de';

export function setLanguage(lang: Language): void {
  current = lang;
  document.documentElement.lang = lang;
}

export function getLanguage(): Language {
  return current;
}

/** Texts in the current language. */
export function t(): Dictionary {
  return DICTIONARIES[current];
}

/** Language to use on the very first start: the browser's language if it is German, else English. */
export function defaultLanguage(): Language {
  return (navigator.language || 'de').toLowerCase().startsWith('de') ? 'de' : 'en';
}

/** Keyboard shortcuts as shown on the buttons (key names depend on the language). */
export function keys() {
  const d = t();
  return {
    assemble: 'F9',
    assembleKeep: `${d.keyShift}+F9`,
    step: 'F10',
    stepBack: `${d.keyShift}+F10`,
    microStep: 'F11',
    run: 'F5',
    open: `${d.keyCtrl}+O`,
    save: `${d.keyCtrl}+S`,
  };
}
